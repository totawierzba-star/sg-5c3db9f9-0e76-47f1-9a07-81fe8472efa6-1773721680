function getDisruptionLabel(article: BlogArticleJa) {
  const title = article.title.toLowerCase();

  if (article.ctaPath === "/cancelled-flight" || title.includes("欠航")) {
    return "欠航";
  }

  if (title.includes("オーバーブッキング") || title.includes("搭乗拒否")) {
    return "搭乗拒否";
  }

  if (title.includes("乗り継ぎ")) {
    return "乗り継ぎの失敗";
  }

  return "遅延";
}

